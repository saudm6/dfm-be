// hlcBars returns day bars from high, low, close rows. A row with no close
// (the stochastic sheet lists closes only where %K is computed) closes at its
// low; the open is the close.
func hlcBars(t *testing.T, rows [][3]string) []domain.Bar {
	t.Helper()
	bars := make([]domain.Bar, len(rows))
	for i, r := range rows {
		c := r[2]
		if c == "" {
			c = r[1]
		}
		bars[i] = newBar(t, domain.OneDay, domain.TradingDayStart(2026, 1, 1).AddDate(0, 0, i),
			ohlcv{open: c, high: r[0], low: r[1], close: c, volume: 1})
	}
	return bars
}

